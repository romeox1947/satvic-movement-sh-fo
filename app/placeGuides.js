export function getPlaceGuide(place = '') {
  return placeGuides.find(item => item.matches.test(place)) || null;
}

export function getPlaceMapUrl(place = '', area = '') {
  const guide = getPlaceGuide(place);
  const placeName = guide?.name || place;
  const address = guide?.area || area || 'Pune, Maharashtra, India';
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(`${placeName}, ${address}`)}`;
}
